type Schema = map[string]any

// ---------------------------------------------------------------------------
// Helpers: naming
// ---------------------------------------------------------------------------

var (
	reUpperThenUpperLower = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
	reLowerOrDigitUpper   = regexp.MustCompile(`([a-z0-9])([A-Z])`)
)

func toSnake(name string) string {
	s := reUpperThenUpperLower.ReplaceAllString(name, "${1}_${2}")
	s = reLowerOrDigitUpper.ReplaceAllString(s, "${1}_${2}")
	return strings.ToLower(s)
}

func toPascal(title string) string {
	parts := regexp.MustCompile(`[._]`).Split(title, -1)
	var result strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		runes := []rune(p)
		runes[0] = unicode.ToUpper(runes[0])
		result.WriteString(string(runes))
	}
	return result.String()
}

// goFieldName converts a JSON property name to a Go exported field name.
func goFieldName(propName string) string {
	cleaned := strings.TrimLeft(propName, "$")
	if cleaned == "" {
		cleaned = "_"
	}
	parts := strings.Split(cleaned, "_")
	var result strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		upper := strings.ToUpper(p)
		switch upper {
		case "ID", "URL", "URI", "API", "HTTP", "HTTPS", "JSON", "XML", "SQL",
			"HTML", "CSS", "IP", "TCP", "UDP", "DNS", "SSH", "TLS", "SSL",
			"UUID", "MCP", "SDK", "RNG", "LLM":
			result.WriteString(upper)
		default:
			runes := []rune(p)
			runes[0] = unicode.ToUpper(runes[0])
			result.WriteString(string(runes))
		}
	}
	return result.String()
}

// ---------------------------------------------------------------------------
// Generic prefix detection
// ---------------------------------------------------------------------------

var genericPrefixes []string

func detectGenericPrefixes(titles map[string]bool) []string {
	prefixes := map[string]bool{}
	for title := range titles {
		parts := strings.Split(title, ".")
		for i := 0; i < len(parts)-1; i++ {
			if parts[i] != "" && unicode.IsUpper(rune(parts[i][0])) {
				prefix := strings.Join(parts[:i+1], ".") + "."
				prefixes[prefix] = true
				break
			}
		}
	}
	result := make([]string, 0, len(prefixes))
	for p := range prefixes {
		result = append(result, p)
	}
	sort.Strings(result)
	return result
}

func getGenericBase(title string) string {
	for _, prefix := range genericPrefixes {
		if strings.HasPrefix(title, prefix) && len(title) > len(prefix) {
			return strings.TrimSuffix(prefix, ".")
		}
	}
	return ""
}

// titleToPath maps a schema title to (directory, filename) relative to srcDir.
// e.g. "agent.Agent" → ("agent", "agent")
// e.g. "agent.openrouter.Agent" → ("agent/openrouter", "agent")
// e.g. "ResponseError" → ("", "response_error")
// e.g. "agent.WithFallbacksAndCount.agent.Agent" → ("agent", "with_fallbacks_and_count")
func titleToPath(title string) (string, string) {
	genericBase := getGenericBase(title)
	var parts []string
	if genericBase != "" {
		parts = strings.Split(genericBase, ".")
	} else {
		parts = strings.Split(title, ".")
	}
	typeName := parts[len(parts)-1]
	dirPath := strings.Join(parts[:len(parts)-1], "/")
	fileName := toSnake(typeName)
	return dirPath, fileName
}

// titleToPackageName returns the Go package name for a given directory path.
func titleToPackageName(dirPath string) string {
	if dirPath == "" {
		return "objectiveai"
	}
	parts := strings.Split(dirPath, "/")
	return parts[len(parts)-1]
}

// titleToTypeName returns the short Go type name for use within its package.
// For non-generic types, this is just PascalCase of the final segment.
// For generic types, it includes the generic base + type parameter to be unique.
func titleToTypeName(title string) string {
	dirPath, _ := titleToPath(title)
	// Convert dirPath back to dot notation
	dirDotPrefix := strings.ReplaceAll(dirPath, "/", ".")
	if dirDotPrefix != "" {
		dirDotPrefix += "."
	}
	// Strip the directory prefix from the title to get the remaining segments
	remaining := title
	if strings.HasPrefix(title, dirDotPrefix) {
		remaining = title[len(dirDotPrefix):]
	}
	return toPascal(remaining)
}

// ---------------------------------------------------------------------------
// JSON Schema → Go type conversion (for struct fields)
// ---------------------------------------------------------------------------

func goType(schema Schema, selfTitle string, allTitles map[string]bool) string {
	if schema == nil || len(schema) == 0 {
		return "any"
	}

	if _, ok := schema["$ref"]; ok {
		// All $refs become `any` to avoid cross-package circular imports.
		// The JSONSchema() method emits the correct $ref string.
		return "any"
	}

	if _, ok := schema["enum"]; ok {
		return "string"
	}

	if anyOf, ok := schema["anyOf"].([]any); ok {
		return goTypeAnyOf(anyOf, selfTitle, allTitles)
	}

	if t, ok := schema["type"].(string); ok {
		return goTypeSingle(t, schema, selfTitle, allTitles)
	}

	if _, ok := schema["properties"]; ok {
		return "any"
	}

	return "any"
}

func goTypeAnyOf(anyOf []any, selfTitle string, allTitles map[string]bool) string {
	nonNull := []Schema{}
	hasNull := false
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if isSimpleNull(m) {
			hasNull = true
		} else {
			nonNull = append(nonNull, m)
		}
	}
	if hasNull && len(nonNull) == 1 {
		inner := goType(nonNull[0], selfTitle, allTitles)
		if inner == "any" || strings.HasPrefix(inner, "*") || strings.HasPrefix(inner, "[]") || strings.HasPrefix(inner, "map[") {
			return inner
		}
		return "*" + inner
	}
	return "any"
}

func goTypeSingle(t string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	switch t {
	case "string":
		return "string"
	case "integer":
		return goIntType(schema)
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "null":
		return "any"
	case "array":
		if items, ok := schema["items"].(map[string]any); ok {
			inner := goType(items, selfTitle, allTitles)
			return "[]" + inner
		}
		return "[]any"
	case "object":
		if ap, ok := schema["additionalProperties"]; ok {
			if apMap, ok := ap.(map[string]any); ok {
				valType := goType(apMap, selfTitle, allTitles)
				return "map[string]" + valType
			}
			if ap == true {
				return "map[string]any"
			}
		}
		if _, ok := schema["properties"]; !ok {
			return "map[string]any"
		}
		return "any"
	}
	return "any"
}

func goIntType(schema Schema) string {
	minVal, hasMin := getNumber(schema, "minimum")
	maxVal, hasMax := getNumber(schema, "maximum")
	if hasMin && hasMax {
		if minVal >= 0 && maxVal == math.MaxUint64 {
			return "uint64"
		}
		if minVal >= 0 && maxVal <= math.MaxUint32 {
			return "uint32"
		}
		if minVal >= 0 && maxVal <= math.MaxUint16 {
			return "uint16"
		}
		if minVal >= 0 && maxVal <= math.MaxUint8 {
			return "uint8"
		}
		if minVal >= math.MinInt8 && maxVal <= math.MaxInt8 {
			return "int8"
		}
		if minVal >= math.MinInt16 && maxVal <= math.MaxInt16 {
			return "int16"
		}
		if minVal >= math.MinInt32 && maxVal <= math.MaxInt32 {
			return "int32"
		}
	}
	return "int64"
}

func getNumber(schema Schema, key string) (float64, bool) {
	v, ok := schema[key]
	if !ok {
		return 0, false
	}
	switch n := v.(type) {
	case float64:
		return n, true
	case json.Number:
		f, err := n.Float64()
		if err != nil {
			return 0, false
		}
		return f, true
	case int64:
		return float64(n), true
	}
	return 0, false
}

// ---------------------------------------------------------------------------
// Schema analysis helpers
// ---------------------------------------------------------------------------

func isSimpleNull(v Schema) bool {
	return len(v) == 1 && v["type"] == "null"
}

func isNullable(propSchema Schema) bool {
	anyOf, ok := propSchema["anyOf"].([]any)
	if !ok {
		return false
	}
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if ok && isSimpleNull(m) {
			return true
		}
	}
	return false
}

func getNonNullVariant(propSchema Schema) Schema {
	anyOf, ok := propSchema["anyOf"].([]any)
	if !ok {
		return propSchema
	}
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if !isSimpleNull(m) {
			return m
		}
	}
	return propSchema
}

// ---------------------------------------------------------------------------
// Format JSON values for Go code literals
// ---------------------------------------------------------------------------

func formatJSONValue(v any) string {
	switch val := v.(type) {
	case string:
		return fmt.Sprintf("%q", val)
	case bool:
		if val {
			return "true"
		}
		return "false"
	case float64:
		if val == math.Trunc(val) && !math.IsInf(val, 0) && math.Abs(val) < 1e15 {
			return fmt.Sprintf("json.Number(%q)", strconv.FormatInt(int64(val), 10))
		}
		s := strconv.FormatFloat(val, 'g', -1, 64)
		return fmt.Sprintf("json.Number(%q)", s)
	case json.Number:
		return fmt.Sprintf("json.Number(%q)", val.String())
	case int:
		return fmt.Sprintf("json.Number(%q)", strconv.Itoa(val))
	case int64:
		return fmt.Sprintf("json.Number(%q)", strconv.FormatInt(val, 10))
	case nil:
		return "nil"
	case []any:
		parts := make([]string, len(val))
		for i, item := range val {
			parts[i] = formatJSONValue(item)
		}
		return "[]any{" + strings.Join(parts, ", ") + "}"
	case map[string]any:
		return formatMapLiteral(val)
	default:
		return fmt.Sprintf("%#v", v)
	}
}

func formatMapLiteral(m map[string]any) string {
	if len(m) == 0 {
		return "map[string]any{}"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%q: %s", k, formatJSONValue(m[k]))
	}
	return "map[string]any{" + strings.Join(parts, ", ") + "}"
}

func formatSchemaMapLiteral(schema Schema) string {
	if len(schema) == 0 {
		return "map[string]any{}"
	}

	keywordOrder := []string{
		"title", "description", "type", "enum", "anyOf", "$ref",
		"properties", "additionalProperties", "items",
		"minItems", "maxItems", "minimum", "maximum",
		"pattern", "format", "default",
	}
	keyRank := make(map[string]int)
	for i, k := range keywordOrder {
		keyRank[k] = i
	}

	keys := make([]string, 0, len(schema))
	for k := range schema {
		keys = append(keys, k)
	}
	sort.SliceStable(keys, func(i, j int) bool {
		ri, oki := keyRank[keys[i]]
		rj, okj := keyRank[keys[j]]
		if !oki {
			ri = len(keywordOrder)
		}
		if !okj {
			rj = len(keywordOrder)
		}
		return ri < rj
	})

	var buf strings.Builder
	buf.WriteString("map[string]any{\n")
	for _, k := range keys {
		v := schema[k]
		buf.WriteString(fmt.Sprintf("\t\t\t%q: %s,\n", k, formatJSONValue(v)))
	}
	buf.WriteString("\t\t}")
	return buf.String()
}

// ---------------------------------------------------------------------------
// Generate struct for object schemas
// ---------------------------------------------------------------------------

func generateStruct(typeName string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	properties, _ := schema["properties"].(map[string]any)

	var buf strings.Builder
	buf.WriteString(fmt.Sprintf("type %s struct {\n", typeName))

	propNames := make([]string, 0, len(properties))
	for k := range properties {
		propNames = append(propNames, k)
	}
	sort.Strings(propNames)

	for _, propName := range propNames {
		propSchema, ok := properties[propName].(map[string]any)
		if !ok {
			continue
		}
		fieldName := goFieldName(propName)
		fieldType := resolveFieldType(propSchema, selfTitle, allTitles)

		jsonTag := propName
		if isNullable(propSchema) || propSchema["default"] != nil {
			if _, hasDefault := propSchema["default"]; isNullable(propSchema) || hasDefault {
				jsonTag += ",omitempty"
			}
		}

		buf.WriteString(fmt.Sprintf("\t%s %s `json:%q`\n", fieldName, fieldType, jsonTag))
	}

	buf.WriteString("}\n")
	return buf.String()
}

func resolveFieldType(propSchema Schema, selfTitle string, allTitles map[string]bool) string {
	if isNullable(propSchema) {
		nonNull := getNonNullVariant(propSchema)
		inner := goType(nonNull, selfTitle, allTitles)
		if inner == "any" || strings.HasPrefix(inner, "*") || strings.HasPrefix(inner, "[]") || strings.HasPrefix(inner, "map[") {
			return inner
		}
		return "*" + inner
	}
	return goType(propSchema, selfTitle, allTitles)
}

// ---------------------------------------------------------------------------
// Generate JSONSchema() method
// ---------------------------------------------------------------------------

func generateJSONSchemaMethod(receiverName string, schema Schema, selfTitle string) string {
	var buf strings.Builder

	buf.WriteString(fmt.Sprintf("func (%s) JSONSchema() map[string]any {\n", receiverName))
	buf.WriteString("\treturn map[string]any{\n")

	buf.WriteString(fmt.Sprintf("\t\t\"title\": %q,\n", selfTitle))

	if desc, ok := schema["description"].(string); ok {
		buf.WriteString(fmt.Sprintf("\t\t\"description\": %q,\n", desc))
	}

	hasProps := false
	if _, ok := schema["properties"]; ok {
		hasProps = true
	}
	var anyOfItems []any
	hasAnyOf := false
	if ao, ok := schema["anyOf"].([]any); ok {
		hasAnyOf = true
		anyOfItems = ao
	}
	var refTarget string
	hasRef := false
	if ref, ok := schema["$ref"].(string); ok {
		hasRef = true
		refTarget = ref
	}

	if t, ok := schema["type"].(string); ok {
		buf.WriteString(fmt.Sprintf("\t\t\"type\": %q,\n", t))
	}

	if enumVals, ok := schema["enum"].([]any); ok {
		parts := make([]string, len(enumVals))
		for i, v := range enumVals {
			parts[i] = fmt.Sprintf("%q", v)
		}
		buf.WriteString(fmt.Sprintf("\t\t\"enum\": []any{%s},\n", strings.Join(parts, ", ")))
	}

	// anyOf (top-level or adjacently-tagged)
	if hasAnyOf {
		buf.WriteString("\t\t\"anyOf\": []any{\n")
		for _, v := range anyOfItems {
			m, ok := v.(map[string]any)
			if !ok {
				continue
			}
			buf.WriteString(fmt.Sprintf("\t\t\t%s,\n", formatSchemaMapLiteral(m)))
		}
		buf.WriteString("\t\t},\n")
	}

	// $ref (top-level or adjacently-tagged)
	if hasRef {
		buf.WriteString(fmt.Sprintf("\t\t\"$ref\": %q,\n", refTarget))
	}

	// properties
	if hasProps {
		buf.WriteString("\t\t\"properties\": map[string]any{\n")
		properties, _ := schema["properties"].(map[string]any)
		propNames := make([]string, 0, len(properties))
		for k := range properties {
			propNames = append(propNames, k)
		}
		sort.Strings(propNames)
		for _, propName := range propNames {
			propSchema, ok := properties[propName].(map[string]any)
			if !ok {
				continue
			}
			buf.WriteString(fmt.Sprintf("\t\t\t%q: %s,\n", propName, formatSchemaMapLiteral(propSchema)))
		}
		buf.WriteString("\t\t},\n")

		if ap, ok := schema["additionalProperties"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"additionalProperties\": %s,\n", formatJSONValue(ap)))
		}
	}

	// Non-object, non-anyOf, non-ref top-level keywords
	if !hasProps && !hasAnyOf && !hasRef {
		if items, ok := schema["items"].(map[string]any); ok {
			buf.WriteString(fmt.Sprintf("\t\t\"items\": %s,\n", formatSchemaMapLiteral(items)))
		}
		for _, kw := range []string{"minItems", "maxItems", "minimum", "maximum", "pattern", "format"} {
			if v, ok := schema[kw]; ok {
				buf.WriteString(fmt.Sprintf("\t\t%q: %s,\n", kw, formatJSONValue(v)))
			}
		}
		if ap, ok := schema["additionalProperties"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"additionalProperties\": %s,\n", formatJSONValue(ap)))
		}
	}

	if v, ok := schema["default"]; ok {
		buf.WriteString(fmt.Sprintf("\t\t\"default\": %s,\n", formatJSONValue(v)))
	}

	buf.WriteString("\t}\n")
	buf.WriteString("}\n")

	return buf.String()
}

// ---------------------------------------------------------------------------
// Generate full type code for a schema
// ---------------------------------------------------------------------------

func generateTypeCode(title string, schema Schema, allTitles map[string]bool) string {
	typeName := titleToTypeName(title)
	hasProperties := schema["properties"] != nil

	var buf strings.Builder

	if hasProperties {
		buf.WriteString(generateStruct(typeName, schema, title, allTitles))
		buf.WriteString("\n")
		buf.WriteString(generateJSONSchemaMethod(typeName, schema, title))
	} else {
		// Non-struct types: type alias + Schema helper for JSONSchema() method
		goT := determineGoType(schema, title, allTitles)
		buf.WriteString(fmt.Sprintf("type %s = %s\n\n", typeName, goT))
		helperName := typeName + "Schema"
		buf.WriteString(fmt.Sprintf("type %s struct{}\n\n", helperName))
		buf.WriteString(generateJSONSchemaMethod(helperName, schema, title))
	}

	return buf.String()
}

func determineGoType(schema Schema, title string, allTitles map[string]bool) string {
	if _, ok := schema["anyOf"]; ok {
		anyOf, _ := schema["anyOf"].([]any)
		var nonNull []Schema
		hasNull := false
		for _, v := range anyOf {
			m, ok := v.(map[string]any)
			if !ok {
				continue
			}
			if isSimpleNull(m) {
				hasNull = true
			} else {
				nonNull = append(nonNull, m)
			}
		}
		if hasNull && len(nonNull) == 1 {
			inner := goType(nonNull[0], title, allTitles)
			if inner == "any" || strings.HasPrefix(inner, "*") || strings.HasPrefix(inner, "[]") || strings.HasPrefix(inner, "map[") {
				return inner
			}
			return "*" + inner
		}
		return "any"
	}
	if _, ok := schema["enum"]; ok {
		return "string"
	}
	if _, ok := schema["$ref"]; ok {
		return "any"
	}
	t, _ := schema["type"].(string)
	switch t {
	case "array":
		if items, ok := schema["items"].(map[string]any); ok {
			inner := goType(items, title, allTitles)
			return "[]" + inner
		}
		return "[]any"
	case "object":
		if ap, ok := schema["additionalProperties"]; ok {
			if apMap, ok := ap.(map[string]any); ok {
				valType := goType(apMap, title, allTitles)
				return "map[string]" + valType
			}
			return "map[string]any"
		}
		return "map[string]any"
	case "string":
		return "string"
	case "integer":
		return goIntType(schema)
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	}
	return "any"
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

func main() {
	// Read all schema files
	entries, err := os.ReadDir(schemaDir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error reading schema dir %s: %v\n", schemaDir, err)
		os.Exit(1)
	}

	schemas := map[string]Schema{}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(schemaDir, entry.Name()))
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error reading %s: %v\n", entry.Name(), err)
			os.Exit(1)
		}
		dec := json.NewDecoder(strings.NewReader(string(data)))
		dec.UseNumber()
		var schema Schema
		if err := dec.Decode(&schema); err != nil {
			fmt.Fprintf(os.Stderr, "Error parsing %s: %v\n", entry.Name(), err)
			os.Exit(1)
		}
		if title, ok := schema["title"].(string); ok {
			schemas[title] = schema
		}
	}

	fmt.Printf("Read %d schemas\n", len(schemas))

	allTitlesSet := map[string]bool{}
	for title := range schemas {
		allTitlesSet[title] = true
	}

	genericPrefixes = detectGenericPrefixes(allTitlesSet)

	// Clean previously generated files
	cleanGenerated(srcDir)

	// Group schemas by output file path
	type fileEntry struct {
		title  string
		schema Schema
	}
	fileGroups := map[string][]fileEntry{}
	for title, schema := range schemas {
		dirPath, fileName := titleToPath(title)
		filePath := fileName
		if dirPath != "" {
			filePath = dirPath + "/" + fileName
		}
		fileGroups[filePath] = append(fileGroups[filePath], fileEntry{title, schema})
	}

	// Sort file paths for deterministic output
	filePaths := make([]string, 0, len(fileGroups))
	for fp := range fileGroups {
		filePaths = append(filePaths, fp)
	}
	sort.Strings(filePaths)

	fmt.Printf("Generating %d .go files across packages\n", len(filePaths))

	// Track info for roundtrip test generation
	type testEntry struct {
		title       string
		dirPath     string
		typeName    string
		isStruct    bool
	}
	var testEntries []testEntry

	// Generate each .go file in its proper subdirectory
	for _, filePath := range filePaths {
		fileEntries := fileGroups[filePath]
		sort.Slice(fileEntries, func(i, j int) bool {
			return fileEntries[i].title < fileEntries[j].title
		})

		// Determine directory and package name
		dirPath, _ := titleToPath(fileEntries[0].title)
		pkgName := titleToPackageName(dirPath)

		var modelCodes []string
		for _, entry := range fileEntries {
			code := generateTypeCode(entry.title, entry.schema, allTitlesSet)
			modelCodes = append(modelCodes, code)

			isStruct := entry.schema["properties"] != nil
			testEntries = append(testEntries, testEntry{
				title:    entry.title,
				dirPath:  dirPath,
				typeName: titleToTypeName(entry.title),
				isStruct: isStruct,
			})
		}

		fullCode := strings.Join(modelCodes, "\n")
		needsJSON := strings.Contains(fullCode, "json.Number")

		var fileContent strings.Builder
		fileContent.WriteString(generatedHeader)
		fileContent.WriteString(fmt.Sprintf("package %s\n", pkgName))

		if needsJSON {
			fileContent.WriteString("\nimport \"encoding/json\"\n")
			fileContent.WriteString("\nvar _ json.Number // suppress unused import\n")
		}

		fileContent.WriteString("\n")
		fileContent.WriteString(fullCode)

		fullPath := filepath.Join(srcDir, filepath.FromSlash(filePath)+".go")
		if err := os.MkdirAll(filepath.Dir(fullPath), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "Error creating dir for %s: %v\n", fullPath, err)
			os.Exit(1)
		}
		if err := os.WriteFile(fullPath, []byte(fileContent.String()), 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", fullPath, err)
			os.Exit(1)
		}
	}

	// Sort test entries by title
	sort.Slice(testEntries, func(i, j int) bool {
		return testEntries[i].title < testEntries[j].title
	})

	// Collect unique sub-package directories for imports
	importDirs := map[string]bool{}
	for _, te := range testEntries {
		if te.dirPath != "" {
			importDirs[te.dirPath] = true
		}
	}
	sortedImportDirs := make([]string, 0, len(importDirs))
	for d := range importDirs {
		sortedImportDirs = append(sortedImportDirs, d)
	}
	sort.Strings(sortedImportDirs)

	// Build import alias map: "agent/completions/message" → "agent_completions_message"
	importAlias := map[string]string{}
	for _, d := range sortedImportDirs {
		alias := strings.ReplaceAll(d, "/", "_")
		importAlias[d] = alias
	}

	// Generate roundtrip test
	var testBuf strings.Builder
	testBuf.WriteString(generatedHeader)
	testBuf.WriteString("package objectiveai\n\n")

	testBuf.WriteString("import (\n")
	testBuf.WriteString("\t\"testing\"\n")
	if len(sortedImportDirs) > 0 {
		testBuf.WriteString("\n")
		for _, d := range sortedImportDirs {
			alias := importAlias[d]
			testBuf.WriteString(fmt.Sprintf("\t%s %q\n", alias, goModulePath+"/"+d))
		}
	}
	testBuf.WriteString(")\n\n")

	testBuf.WriteString("func TestRoundtrip(t *testing.T) {\n")
	testBuf.WriteString("\tfor _, title := range allTitlesSorted {\n")
	testBuf.WriteString("\t\tt.Run(title, func(t *testing.T) {\n")
	testBuf.WriteString("\t\t\tvar schema map[string]any\n")
	testBuf.WriteString("\t\t\tswitch title {\n")

	for _, te := range testEntries {
		testBuf.WriteString(fmt.Sprintf("\t\t\tcase %q:\n", te.title))
		var qualifiedName string
		if te.dirPath == "" {
			// Root package — no alias needed
			if te.isStruct {
				qualifiedName = te.typeName
			} else {
				qualifiedName = te.typeName + "Schema"
			}
		} else {
			alias := importAlias[te.dirPath]
			if te.isStruct {
				qualifiedName = alias + "." + te.typeName
			} else {
				qualifiedName = alias + "." + te.typeName + "Schema"
			}
		}
		testBuf.WriteString(fmt.Sprintf("\t\t\t\tschema = %s{}.JSONSchema()\n", qualifiedName))
	}

	testBuf.WriteString("\t\t\tdefault:\n")
	testBuf.WriteString("\t\t\t\tt.Fatalf(\"no schema provider for %q\", title)\n")
	testBuf.WriteString("\t\t\t}\n")
	testBuf.WriteString("\t\t\tassertSchemaMatches(t, title, schema)\n")
	testBuf.WriteString("\t\t})\n")
	testBuf.WriteString("\t}\n")
	testBuf.WriteString("}\n")

	testPath := filepath.Join(srcDir, "roundtrip_test.go")
	if err := os.WriteFile(testPath, []byte(testBuf.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing roundtrip test: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %d type files + roundtrip test (%d sub-packages)\n", len(filePaths), len(importDirs))
	fmt.Println("Done!")
}

// ---------------------------------------------------------------------------
// Clean previously generated files
// ---------------------------------------------------------------------------

func cleanGenerated(dir string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return
	}
	for _, entry := range entries {
		fullPath := filepath.Join(dir, entry.Name())
		if entry.IsDir() {
			// Don't recurse into scripts/
			if entry.Name() == "scripts" {
				continue
			}
			cleanGenerated(fullPath)
			remaining, _ := os.ReadDir(fullPath)
			if len(remaining) == 0 {
				os.Remove(fullPath)
			}
			continue
		}
		if !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		data, err := os.ReadFile(fullPath)
		if err != nil {
			continue
		}
		if len(data) >= 128 && strings.Contains(string(data[:128]), "THIS FILE IS AUTO-GENERATED") {
			os.Remove(fullPath)
		}
	}
}
