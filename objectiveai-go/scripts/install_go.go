// goType converts a JSON schema node to a Go type string.
// selfTitle is the title of the schema being generated (for self-refs).
// allTitles is the set of all known schema titles.
func goType(schema Schema, selfTitle string, allTitles map[string]bool) string {
	if schema == nil || len(schema) == 0 {
		return "any"
	}

	// $ref
	if ref, ok := schema["$ref"].(string); ok {
		if ref == "#" {
			return toPascal(selfTitle)
		}
		return toPascal(ref)
	}

	// enum
	if _, ok := schema["enum"]; ok {
		return "string" // all enums in this schema set are string enums
	}

	// anyOf
	if anyOf, ok := schema["anyOf"].([]any); ok {
		return goTypeAnyOf(anyOf, selfTitle, allTitles)
	}

	// type
	if t, ok := schema["type"].(string); ok {
		return goTypeSingle(t, schema, selfTitle, allTitles)
	}

	if _, ok := schema["properties"]; ok {
		return goTypeSingle("object", schema, selfTitle, allTitles)
	}

	return "any"
}

func goTypeAnyOf(anyOf []any, selfTitle string, allTitles map[string]bool) string {
	// Check for nullable (exactly 2 variants, one null)
	nullIdx := -1
	nonNull := []Schema{}
	for i, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if m["type"] == "null" && len(m) == 1 {
			nullIdx = i
		} else {
			nonNull = append(nonNull, m)
		}
	}

	if nullIdx >= 0 && len(nonNull) == 1 {
		inner := goType(nonNull[0], selfTitle, allTitles)
		if inner == "any" || strings.HasPrefix(inner, "*") || strings.HasPrefix(inner, "[]") || strings.HasPrefix(inner, "map[") {
			return inner
		}
		return "*" + inner
	}

	// General union — not representable as a single Go type inline.
	// Return "any" — the variant handling is done at the type level.
	return "any"
}

func goTypeSingle(t string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	switch t {
	case "string":
		if schema["format"] == "date-time" {
			return "string" // Keep as string for roundtrip (Go time.Time doesn't roundtrip to JSON Schema)
		}
		if schema["format"] == "uuid" {
			return "string"
		}
		return "string"
	case "integer":
		return goIntType(schema)
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "null":
		return "any"
	case "array":
		if items, ok := schema["items"].(map[string]any); ok {
			inner := goType(items, selfTitle, allTitles)
			return "[]" + inner
		}
		return "[]any"
	case "object":
		if ap, ok := schema["additionalProperties"]; ok {
			if apMap, ok := ap.(map[string]any); ok {
				valType := goType(apMap, selfTitle, allTitles)
				return "map[string]" + valType
			}
			if ap == true {
				return "map[string]any"
			}
		}
		if _, ok := schema["properties"]; !ok {
			return "map[string]any"
		}
		return "any" // object with properties = struct, handled elsewhere
	}
	return "any"
}

func goIntType(schema Schema) string {
	minVal, hasMin := getNumber(schema, "minimum")
	maxVal, hasMax := getNumber(schema, "maximum")
	if hasMin && hasMax {
		if minVal >= 0 && maxVal == math.MaxUint64 {
			return "uint64"
		}
		if minVal >= 0 && maxVal <= math.MaxUint32 {
			return "uint32"
		}
		if minVal >= 0 && maxVal <= math.MaxUint16 {
			return "uint16"
		}
		if minVal >= 0 && maxVal <= math.MaxUint8 {
			return "uint8"
		}
		if minVal >= math.MinInt8 && maxVal <= math.MaxInt8 {
			return "int8"
		}
		if minVal >= math.MinInt16 && maxVal <= math.MaxInt16 {
			return "int16"
		}
		if minVal >= math.MinInt32 && maxVal <= math.MaxInt32 {
			return "int32"
		}
	}
	return "int64"
}

func getNumber(schema Schema, key string) (float64, bool) {
	v, ok := schema[key]
	if !ok {
		return 0, false
	}
	switch n := v.(type) {
	case float64:
		return n, true
	case json.Number:
		f, err := n.Float64()
		if err != nil {
			return 0, false
		}
		return f, true
	case int64:
		return float64(n), true
	}
	return 0, false
}

// ---------------------------------------------------------------------------
// Collecting $ref dependencies
// ---------------------------------------------------------------------------

func collectRefs(schema any, refs map[string]bool) {
	switch v := schema.(type) {
	case map[string]any:
		if ref, ok := v["$ref"].(string); ok && ref != "#" {
			refs[ref] = true
		}
		for _, val := range v {
			collectRefs(val, refs)
		}
	case []any:
		for _, item := range v {
			collectRefs(item, refs)
		}
	}
}

