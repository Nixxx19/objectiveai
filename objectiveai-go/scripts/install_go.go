// isNullable checks if a property schema is nullable (anyOf with null variant).
func isNullable(propSchema Schema) bool {
	anyOf, ok := propSchema["anyOf"].([]any)
	if !ok {
		return false
	}
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if m["type"] == "null" && len(m) == 1 {
			return true
		}
	}
	return false
}

// getNonNullVariant returns the non-null variant from a nullable anyOf.
func getNonNullVariant(propSchema Schema) Schema {
	anyOf, ok := propSchema["anyOf"].([]any)
	if !ok {
		return propSchema
	}
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if !(m["type"] == "null" && len(m) == 1) {
			return m
		}
	}
	return propSchema
}

// isSimpleNullVariant checks if a variant is just {"type": "null"}.
func isSimpleNullVariant(v Schema) bool {
	return len(v) == 1 && v["type"] == "null"
}

// needsVariantTypes checks if an anyOf needs variant type generation.
func needsVariantTypes(anyOf []any) bool {
	if len(anyOf) > 2 {
		return true
	}
	if len(anyOf) == 2 {
		for _, v := range anyOf {
			m, ok := v.(map[string]any)
			if ok && isSimpleNullVariant(m) {
				return false
			}
		}
		return true
	}
	return false
}

// formatJSONValue formats a Go literal for use in JSONSchema() methods.
// Uses json.Number strings for large integers to preserve precision.
func formatJSONValue(v any) string {
	switch val := v.(type) {
	case string:
		return fmt.Sprintf("%q", val)
	case bool:
		if val {
			return "true"
		}
		return "false"
	case float64:
		// Check if it's actually an integer
		if val == math.Trunc(val) && !math.IsInf(val, 0) && math.Abs(val) < 1e15 {
			return fmt.Sprintf("json.Number(%q)", strconv.FormatInt(int64(val), 10))
		}
		// Format as float, preserving the exact representation
		s := strconv.FormatFloat(val, 'g', -1, 64)
		return fmt.Sprintf("json.Number(%q)", s)
	case json.Number:
		return fmt.Sprintf("json.Number(%q)", val.String())
	case int:
		return fmt.Sprintf("json.Number(%q)", strconv.Itoa(val))
	case int64:
		return fmt.Sprintf("json.Number(%q)", strconv.FormatInt(val, 10))
	case nil:
		return "nil"
	case []any:
		parts := make([]string, len(val))
		for i, item := range val {
			parts[i] = formatJSONValue(item)
		}
		return "[]any{" + strings.Join(parts, ", ") + "}"
	case map[string]any:
		return formatMapLiteral(val)
	default:
		return fmt.Sprintf("%#v", v)
	}
}

func formatMapLiteral(m map[string]any) string {
	if len(m) == 0 {
		return "map[string]any{}"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%q: %s", k, formatJSONValue(m[k]))
	}
	return "map[string]any{" + strings.Join(parts, ", ") + "}"
}

// formatSchemaMapLiteral generates Go code for a schema map literal,
// using the canonical keyword ordering.
func formatSchemaMapLiteral(schema Schema) string {
	if len(schema) == 0 {
		return "map[string]any{}"
	}

	keywordOrder := []string{
		"title", "description", "type", "enum", "anyOf", "$ref",
		"properties", "additionalProperties", "items",
		"minItems", "maxItems", "minimum", "maximum",
		"pattern", "format", "default",
	}
	keyRank := make(map[string]int)
	for i, k := range keywordOrder {
		keyRank[k] = i
	}

	keys := make([]string, 0, len(schema))
	for k := range schema {
		keys = append(keys, k)
	}
	sort.SliceStable(keys, func(i, j int) bool {
		ri, oki := keyRank[keys[i]]
		rj, okj := keyRank[keys[j]]
		if !oki {
			ri = len(keywordOrder)
		}
		if !okj {
			rj = len(keywordOrder)
		}
		return ri < rj
	})

	var buf strings.Builder
	buf.WriteString("map[string]any{\n")
	for _, k := range keys {
		v := schema[k]
		buf.WriteString(fmt.Sprintf("\t\t\t%q: %s,\n", k, formatJSONValue(v)))
	}
	buf.WriteString("\t\t}")
	return buf.String()
}

// ---------------------------------------------------------------------------
// Generate struct for object with properties
// ---------------------------------------------------------------------------

func generateStruct(pascalName string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	properties, _ := schema["properties"].(map[string]any)

	var buf strings.Builder

	// Struct definition
	buf.WriteString(fmt.Sprintf("type %s struct {\n", pascalName))

	// Sort property names alphabetically (matching JSON Schema)
	propNames := make([]string, 0, len(properties))
	for k := range properties {
		propNames = append(propNames, k)
	}
	sort.Strings(propNames)

	for _, propName := range propNames {
		propSchema, ok := properties[propName].(map[string]any)
		if !ok {
			continue
		}
		fieldName := goFieldName(propName)
		fieldType := resolveFieldType(propSchema, selfTitle, allTitles)

		// JSON tag
		jsonTag := propName
		if isNullable(propSchema) {
			jsonTag += ",omitempty"
		}
		// Fields with defaults should also be omitempty
		if _, hasDefault := propSchema["default"]; hasDefault {
			if !strings.Contains(jsonTag, "omitempty") {
				jsonTag += ",omitempty"
			}
		}

		tags := fmt.Sprintf("`json:%q`", jsonTag)

		buf.WriteString(fmt.Sprintf("\t%s %s %s\n", fieldName, fieldType, tags))
	}

	buf.WriteString("}\n")

	return buf.String()
}

// resolveFieldType determines the Go type for a struct field.
func resolveFieldType(propSchema Schema, selfTitle string, allTitles map[string]bool) string {
	// Check for nullable
	if isNullable(propSchema) {
		nonNull := getNonNullVariant(propSchema)
		inner := goType(nonNull, selfTitle, allTitles)
		if inner == "any" || strings.HasPrefix(inner, "*") || strings.HasPrefix(inner, "[]") || strings.HasPrefix(inner, "map[") {
			return inner
		}
		return "*" + inner
	}

	// Check for $ref with other properties (adjacently-tagged)
	if ref, ok := propSchema["$ref"].(string); ok {
		// Direct $ref at property level — just reference the type
		if ref == "#" {
			return "*" + toPascal(selfTitle)
		}
		return toPascal(ref)
	}

	return goType(propSchema, selfTitle, allTitles)
}

// ---------------------------------------------------------------------------
// Generate JSONSchema() method
// ---------------------------------------------------------------------------

func generateJSONSchemaMethod(pascalName string, schema Schema, selfTitle string, allTitles map[string]bool) string {
	var buf strings.Builder

	buf.WriteString(fmt.Sprintf("func (%s) JSONSchema() map[string]any {\n", pascalName))
	buf.WriteString("\treturn map[string]any{\n")

	// title
	buf.WriteString(fmt.Sprintf("\t\t\"title\": %q,\n", selfTitle))

	// description
	if desc, ok := schema["description"].(string); ok {
		buf.WriteString(fmt.Sprintf("\t\t\"description\": %q,\n", desc))
	}

	// Determine schema structure
	hasProps := false
	if _, ok := schema["properties"]; ok {
		hasProps = true
	}
	hasAnyOf := false
	var anyOfItems []any
	if ao, ok := schema["anyOf"].([]any); ok {
		hasAnyOf = true
		anyOfItems = ao
	}
	hasRef := false
	var refTarget string
	if ref, ok := schema["$ref"].(string); ok {
		hasRef = true
		refTarget = ref
	}

	// type
	if t, ok := schema["type"].(string); ok {
		buf.WriteString(fmt.Sprintf("\t\t\"type\": %q,\n", t))
	}

	// enum
	if enumVals, ok := schema["enum"].([]any); ok {
		parts := make([]string, len(enumVals))
		for i, v := range enumVals {
			parts[i] = fmt.Sprintf("%q", v)
		}
		buf.WriteString(fmt.Sprintf("\t\t\"enum\": []any{%s},\n", strings.Join(parts, ", ")))
	}

	// anyOf
	if hasAnyOf && !hasProps && !hasRef {
		buf.WriteString("\t\t\"anyOf\": []any{\n")
		for _, v := range anyOfItems {
			m, ok := v.(map[string]any)
			if !ok {
				continue
			}
			buf.WriteString(fmt.Sprintf("\t\t\t%s,\n", formatSchemaMapLiteral(m)))
		}
		buf.WriteString("\t\t},\n")
	}

	// $ref (top-level only, not adjacently-tagged)
	if hasRef && !hasProps {
		buf.WriteString(fmt.Sprintf("\t\t\"$ref\": %q,\n", refTarget))
	}

	// For objects with properties: type + anyOf/ref + properties + additionalProperties
	if hasProps {
		// anyOf (adjacently-tagged)
		if hasAnyOf {
			buf.WriteString("\t\t\"anyOf\": []any{\n")
			for _, v := range anyOfItems {
				m, ok := v.(map[string]any)
				if !ok {
					continue
				}
				buf.WriteString(fmt.Sprintf("\t\t\t%s,\n", formatSchemaMapLiteral(m)))
			}
			buf.WriteString("\t\t},\n")
		}
		// $ref (adjacently-tagged)
		if hasRef {
			buf.WriteString(fmt.Sprintf("\t\t\"$ref\": %q,\n", refTarget))
		}

		// properties
		buf.WriteString("\t\t\"properties\": map[string]any{\n")
		properties, _ := schema["properties"].(map[string]any)
		propNames := make([]string, 0, len(properties))
		for k := range properties {
			propNames = append(propNames, k)
		}
		sort.Strings(propNames)
		for _, propName := range propNames {
			propSchema, ok := properties[propName].(map[string]any)
			if !ok {
				continue
			}
			buf.WriteString(fmt.Sprintf("\t\t\t%q: %s,\n", propName, formatSchemaMapLiteral(propSchema)))
		}
		buf.WriteString("\t\t},\n")

		// additionalProperties
		if ap, ok := schema["additionalProperties"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"additionalProperties\": %s,\n", formatJSONValue(ap)))
		}
	}

	// For non-object top-level types
	if !hasProps && !hasAnyOf && !hasRef {
		// items (array type)
		if items, ok := schema["items"].(map[string]any); ok {
			buf.WriteString(fmt.Sprintf("\t\t\"items\": %s,\n", formatSchemaMapLiteral(items)))
		}

		// minItems, maxItems
		if v, ok := schema["minItems"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"minItems\": %s,\n", formatJSONValue(v)))
		}
		if v, ok := schema["maxItems"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"maxItems\": %s,\n", formatJSONValue(v)))
		}

		// minimum, maximum
		if v, ok := schema["minimum"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"minimum\": %s,\n", formatJSONValue(v)))
		}
		if v, ok := schema["maximum"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"maximum\": %s,\n", formatJSONValue(v)))
		}

		// pattern
		if v, ok := schema["pattern"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"pattern\": %s,\n", formatJSONValue(v)))
		}

		// format
		if v, ok := schema["format"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"format\": %s,\n", formatJSONValue(v)))
		}

		// additionalProperties (for map types)
		if ap, ok := schema["additionalProperties"]; ok {
			buf.WriteString(fmt.Sprintf("\t\t\"additionalProperties\": %s,\n", formatJSONValue(ap)))
		}
	}

	// default
	if v, ok := schema["default"]; ok {
		buf.WriteString(fmt.Sprintf("\t\t\"default\": %s,\n", formatJSONValue(v)))
	}

	buf.WriteString("\t}\n")
	buf.WriteString("}\n")

	return buf.String()
}

// ---------------------------------------------------------------------------
// Generate full type code for a schema
// ---------------------------------------------------------------------------

func generateTypeCode(title string, schema Schema, allTitles map[string]bool) (string, map[string]bool) {
	refs := map[string]bool{}
	collectRefs(schema, refs)

	pascalName := toPascal(title)

	hasProperties := false
	if _, ok := schema["properties"]; ok {
		hasProperties = true
	}
	hasAnyOf := false
	if _, ok := schema["anyOf"]; ok {
		hasAnyOf = true
	}
	hasRef := false
	if _, ok := schema["$ref"]; ok {
		hasRef = true
	}

	var buf strings.Builder

	// Case 1: Object with properties (possibly with anyOf or $ref for adjacently-tagged)
	if hasProperties {
		structCode := generateStruct(pascalName, schema, title, allTitles)
		buf.WriteString(structCode)
		buf.WriteString("\n")
		methodCode := generateJSONSchemaMethod(pascalName, schema, title, allTitles)
		buf.WriteString(methodCode)
		return buf.String(), refs
	}

	// Case 2: anyOf without properties — type alias or variant union
	if hasAnyOf {
		anyOf, _ := schema["anyOf"].([]any)

		// Simple type alias for the anyOf
		goTypeName := determineAnyOfGoType(anyOf, title, allTitles)
		buf.WriteString(fmt.Sprintf("type %s = %s\n", pascalName, goTypeName))
		buf.WriteString("\n")
		// For type aliases we need a wrapper to hold the JSONSchema method
		// since Go doesn't allow methods on type aliases. Use a helper struct.
		helperName := pascalName + "Schema"
		buf.WriteString(fmt.Sprintf("type %s struct{}\n\n", helperName))
		methodCode := generateJSONSchemaMethod(helperName, schema, title, allTitles)
		buf.WriteString(methodCode)
		return buf.String(), refs
	}

	// Case 3: enum only
	if _, ok := schema["enum"]; ok {
		buf.WriteString(fmt.Sprintf("type %s = string\n", pascalName))
		buf.WriteString("\n")
		helperName := pascalName + "Schema"
		buf.WriteString(fmt.Sprintf("type %s struct{}\n\n", helperName))
		methodCode := generateJSONSchemaMethod(helperName, schema, title, allTitles)
		buf.WriteString(methodCode)
		return buf.String(), refs
	}

	// Case 4: $ref at top level
	if hasRef {
		refTarget, _ := schema["$ref"].(string)
		if refTarget == "#" {
			refTarget = title
		}
		buf.WriteString(fmt.Sprintf("type %s = %s\n", pascalName, toPascal(refTarget)))
		buf.WriteString("\n")
		helperName := pascalName + "Schema"
		buf.WriteString(fmt.Sprintf("type %s struct{}\n\n", helperName))
		methodCode := generateJSONSchemaMethod(helperName, schema, title, allTitles)
		buf.WriteString(methodCode)
		return buf.String(), refs
	}

	// Case 5: Primitive types, arrays, maps
	t, _ := schema["type"].(string)
	switch t {
	case "array":
		innerType := "any"
		if items, ok := schema["items"].(map[string]any); ok {
			innerType = goType(items, title, allTitles)
		}
		buf.WriteString(fmt.Sprintf("type %s = []%s\n", pascalName, innerType))
	case "object":
		if ap, ok := schema["additionalProperties"]; ok {
			if apMap, ok := ap.(map[string]any); ok {
				valType := goType(apMap, title, allTitles)
				buf.WriteString(fmt.Sprintf("type %s = map[string]%s\n", pascalName, valType))
			} else {
				buf.WriteString(fmt.Sprintf("type %s = map[string]any\n", pascalName))
			}
		} else {
			buf.WriteString(fmt.Sprintf("type %s struct{}\n", pascalName))
		}
	case "string":
		buf.WriteString(fmt.Sprintf("type %s = string\n", pascalName))
	case "integer":
		goT := goIntType(schema)
		buf.WriteString(fmt.Sprintf("type %s = %s\n", pascalName, goT))
	case "number":
		buf.WriteString(fmt.Sprintf("type %s = float64\n", pascalName))
	case "boolean":
		buf.WriteString(fmt.Sprintf("type %s = bool\n", pascalName))
	default:
		buf.WriteString(fmt.Sprintf("type %s = any\n", pascalName))
	}

	buf.WriteString("\n")
	helperName := pascalName + "Schema"
	buf.WriteString(fmt.Sprintf("type %s struct{}\n\n", helperName))
	methodCode := generateJSONSchemaMethod(helperName, schema, title, allTitles)
	buf.WriteString(methodCode)

	return buf.String(), refs
}

// determineAnyOfGoType returns the Go type for an anyOf schema.
func determineAnyOfGoType(anyOf []any, selfTitle string, allTitles map[string]bool) string {
	// Check for nullable
	var nonNull []Schema
	hasNull := false
	for _, v := range anyOf {
		m, ok := v.(map[string]any)
		if !ok {
			continue
		}
		if isSimpleNullVariant(m) {
			hasNull = true
		} else {
			nonNull = append(nonNull, m)
		}
	}
	if hasNull && len(nonNull) == 1 {
		inner := goType(nonNull[0], selfTitle, allTitles)
		if inner == "any" || strings.HasPrefix(inner, "*") || strings.HasPrefix(inner, "[]") || strings.HasPrefix(inner, "map[") {
			return inner
		}
		return "*" + inner
	}
	// General union = any
	return "any"
}

