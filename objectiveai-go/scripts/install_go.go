// Generate roundtrip test
// ---------------------------------------------------------------------------

func generateRoundtripTest(allTitles []string) string {
	var buf strings.Builder

	buf.WriteString(generatedHeader)
	buf.WriteString("package objectiveai\n\n")
	buf.WriteString("import \"testing\"\n\n")

	buf.WriteString("// schemaProviders maps schema titles to their JSONSchema() providers.\n")
	buf.WriteString("var schemaProviders = map[string]func() map[string]any{\n")

	for _, title := range allTitles {
		pascalName := toPascal(title)
		// Determine if this is a struct type (has properties) or a type alias (needs Schema helper)
		// We always generate a Schema helper for non-struct types, so we can use that uniformly.
		// For struct types, the JSONSchema() method is on the struct itself.
		// To simplify, we check at generation time. For the test file, we just need to know
		// which type has the method.
		buf.WriteString(fmt.Sprintf("\t%q: func() map[string]any { return %s{}.JSONSchema() },\n", title, pascalName+"Schema"))
	}

	buf.WriteString("}\n\n")

	buf.WriteString("func TestRoundtrip(t *testing.T) {\n")
	buf.WriteString("\tfor _, title := range allTitlesSorted {\n")
	buf.WriteString("\t\tt.Run(title, func(t *testing.T) {\n")
	buf.WriteString("\t\t\tprovider, ok := schemaProviders[title]\n")
	buf.WriteString("\t\t\tif !ok {\n")
	buf.WriteString("\t\t\t\tt.Fatalf(\"no schema provider for %q\", title)\n")
	buf.WriteString("\t\t\t}\n")
	buf.WriteString("\t\t\tconverted := provider()\n")
	buf.WriteString("\t\t\tassertSchemaMatches(t, title, converted)\n")
	buf.WriteString("\t\t})\n")
	buf.WriteString("\t}\n")
	buf.WriteString("}\n")

	return buf.String()
}

