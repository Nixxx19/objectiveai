type Schema = map[string]any

// ---------------------------------------------------------------------------
// Naming helpers
// ---------------------------------------------------------------------------

var (
	reUpperUpper = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
	reLowerUpper = regexp.MustCompile(`([a-z0-9])([A-Z])`)
)

func toSnake(name string) string {
	s := reUpperUpper.ReplaceAllString(name, "${1}_${2}")
	s = reLowerUpper.ReplaceAllString(s, "${1}_${2}")
	return strings.ToLower(s)
}

// toPascal converts a dot-separated title to PascalCase.
// "agent.openrouter.Agent" → "AgentOpenrouterAgent"
func toPascal(title string) string {
	parts := regexp.MustCompile(`[._]`).Split(title, -1)
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		runes := []rune(p)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}

// goFieldName converts a JSON property name to an exported Go field name.
func goFieldName(propName string) string {
	cleaned := strings.TrimLeft(propName, "$")
	if cleaned == "" {
		cleaned = "Val"
	}
	parts := strings.Split(cleaned, "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		upper := strings.ToUpper(p)
		switch upper {
		case "ID", "URL", "URI", "API", "HTTP", "HTTPS", "JSON", "XML", "SQL",
			"HTML", "CSS", "IP", "TCP", "UDP", "DNS", "SSH", "TLS", "SSL",
			"UUID", "MCP", "SDK", "RNG", "LLM":
			b.WriteString(upper)
		default:
			runes := []rune(p)
			runes[0] = unicode.ToUpper(runes[0])
			b.WriteString(string(runes))
		}
	}
	return b.String()
}

// ---------------------------------------------------------------------------
// Generic prefix detection
// ---------------------------------------------------------------------------

var genericPrefixes []string

func detectGenericPrefixes(titles map[string]bool) []string {
	prefixes := map[string]bool{}
	for title := range titles {
		parts := strings.Split(title, ".")
		for i := 0; i < len(parts)-1; i++ {
			if parts[i] != "" && unicode.IsUpper(rune(parts[i][0])) {
				prefixes[strings.Join(parts[:i+1], ".")+"." ] = true
				break
			}
		}
	}
	result := make([]string, 0, len(prefixes))
	for p := range prefixes {
		result = append(result, p)
	}
	sort.Strings(result)
	return result
}

func getGenericBase(title string) string {
	for _, prefix := range genericPrefixes {
		if strings.HasPrefix(title, prefix) && len(title) > len(prefix) {
			return strings.TrimSuffix(prefix, ".")
		}
	}
	return ""
}

// titleToFilePath returns the flat file name (without .go extension).
// "agent.openrouter.Agent" → "agent_openrouter_agent"
// "ResponseError" → "response_error"
// Generic: "agent.WithFallbacksAndCount.agent.Agent" → "agent_with_fallbacks_and_count"
func titleToFilePath(title string) string {
	genericBase := getGenericBase(title)
	var parts []string
	if genericBase != "" {
		parts = strings.Split(genericBase, ".")
	} else {
		parts = strings.Split(title, ".")
	}
	snakeParts := make([]string, len(parts))
	for i, p := range parts {
		snakeParts[i] = toSnake(p)
	}
	return strings.Join(snakeParts, "_")
}

