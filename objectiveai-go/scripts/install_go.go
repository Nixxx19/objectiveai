func formatJSONValue(v any) string {
	switch val := v.(type) {
	case string:
		return fmt.Sprintf("%q", val)
	case bool:
		if val {
			return "true"
		}
		return "false"
	case float64:
		if val == math.Trunc(val) && !math.IsInf(val, 0) && math.Abs(val) < 1e15 {
			return fmt.Sprintf("json.Number(%q)", strconv.FormatInt(int64(val), 10))
		}
		return fmt.Sprintf("json.Number(%q)", strconv.FormatFloat(val, 'g', -1, 64))
	case json.Number:
		return fmt.Sprintf("json.Number(%q)", val.String())
	case int:
		return fmt.Sprintf("json.Number(%q)", strconv.Itoa(val))
	case int64:
		return fmt.Sprintf("json.Number(%q)", strconv.FormatInt(val, 10))
	case nil:
		return "nil"
	case []any:
		parts := make([]string, len(val))
		for i, item := range val {
			parts[i] = formatJSONValue(item)
		}
		return "[]any{" + strings.Join(parts, ", ") + "}"
	case map[string]any:
		return formatMapLiteral(val)
	default:
		return fmt.Sprintf("%#v", v)
	}
}

func formatMapLiteral(m map[string]any) string {
	if len(m) == 0 {
		return "map[string]any{}"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%q: %s", k, formatJSONValue(m[k]))
	}
	return "map[string]any{" + strings.Join(parts, ", ") + "}"
}


func formatTagNumber(v any) string {
	switch n := v.(type) {
	case json.Number:
		return n.String()
	case float64:
		if n == math.Trunc(n) && !math.IsInf(n, 0) && math.Abs(n) < 1e15 {
			return strconv.FormatInt(int64(n), 10)
		}
		return strconv.FormatFloat(n, 'g', -1, 64)
	default:
		return fmt.Sprintf("%v", v)
	}
}

func formatTagDefault(v any) string {
	switch val := v.(type) {
	case string:
		return val
	case bool:
		return fmt.Sprintf("%v", val)
	case json.Number:
		return val.String()
	case float64:
		return strconv.FormatFloat(val, 'g', -1, 64)
	case nil:
		return "null"
	default:
		b, _ := json.Marshal(val)
		return string(b)
	}
}

