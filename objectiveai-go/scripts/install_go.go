//
// Reads JSON schemas from objectiveai-json-schema/ and generates Go type files
// in objectiveai-go/ with proper package structure, struct tags, and JSONSchema()
// methods for roundtrip testing.
//
// This is the Go equivalent of objectiveai-py/scripts/install_pydantic.py.
//
//go:build ignore

