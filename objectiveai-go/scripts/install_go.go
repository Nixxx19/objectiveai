// ---------------------------------------------------------------------------
// Paths
// ---------------------------------------------------------------------------

var (
	scriptDir string
	rootDir   string
	schemaDir string
	srcDir    string
)

func init() {
	ex, err := os.Executable()
	if err != nil {
		// fallback: use working directory
		scriptDir, _ = os.Getwd()
	} else {
		scriptDir = filepath.Dir(ex)
	}
	// When run via `go run`, the executable is in a temp dir.
	// Use the working directory + known relative path instead.
	wd, _ := os.Getwd()
	// Detect if we're in objectiveai-go or its scripts/ subdirectory
	if filepath.Base(wd) == "scripts" {
		rootDir = filepath.Dir(filepath.Dir(wd))
	} else if filepath.Base(wd) == "objectiveai-go" {
		rootDir = filepath.Dir(wd)
	} else {
		// Assume we're in the repo root
		rootDir = wd
	}
	schemaDir = filepath.Join(rootDir, "objectiveai-json-schema")
	srcDir = filepath.Join(rootDir, "objectiveai-go")
}

