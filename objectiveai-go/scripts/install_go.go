// goDocComment formats a description string as Go doc comment lines.
// Returns empty string if description is empty.
func goDocComment(description string, indent string) string {
	if description == "" {
		return ""
	}
	var b strings.Builder
	for _, line := range strings.Split(description, "\n") {
		if line == "" {
			b.WriteString(indent + "//\n")
		} else {
			b.WriteString(indent + "// " + line + "\n")
		}
	}
	return b.String()
}

