string GenerateType(string title, JsonElement schema, HashSet<string> usings)
{
    var pascalName = TitleToPascal(title);
    var hasProperties = schema.TryGetProperty("properties", out var propsEl);
    var hasAnyOf = schema.TryGetProperty("anyOf", out var anyOfEl);
    var hasRef = schema.TryGetProperty("$ref", out _);
    var hasType = schema.TryGetProperty("type", out var typeEl);
    var description = GetString(schema, "description");

    // Case 1: anyOf at top level without properties
    if (hasAnyOf && !hasProperties && !hasRef)
    {
        var variants = anyOfEl.EnumerateArray().ToList();

        // Check if all variants are single-value string enums with descriptions → C# enum
        if (IsStringEnumAnyOf(variants))
        {
            return GenerateEnum(title, pascalName, description, variants, usings);
        }

        // Check if all variants are pure $ref → marker interface
        if (variants.All(v => v.TryGetProperty("$ref", out _) && v.EnumerateObject().Count() == 1))
        {
            return GenerateMarkerInterface(title, pascalName, description, variants, usings);
        }

        // Check for nullable (2 variants, one null)
        if (IsNullable(variants))
        {
            // Top-level nullable → wrapper class
            var nonNull = variants.First(v => GetString(v, "type") != "null");
            return GenerateNullableWrapper(title, pascalName, description, nonNull, usings);
        }

        // General anyOf → marker interface with variant classes
        return GenerateAnyOfInterface(title, pascalName, description, variants, usings);
    }

    // Case 2: Object with properties
    if (hasProperties || (hasType && typeEl.GetString() == "object"))
    {
        // Check for adjacently-tagged: properties + anyOf
        if (hasAnyOf)
        {
            return GenerateFlattenedModel(title, pascalName, description, schema, propsEl, anyOfEl, usings);
        }
        // Check for properties + $ref
        if (hasRef)
        {
            return GenerateFlattenedRefModel(title, pascalName, description, schema, propsEl, usings);
        }
        return GenerateObjectClass(title, pascalName, description, schema, propsEl, usings);
    }

    // Case 3: enum at top level
    if (schema.TryGetProperty("enum", out var enumEl))
    {
        var enumType = GetString(schema, "type");
        if (enumType == "string")
        {
            var values = enumEl.EnumerateArray().Select(e => e.GetString()!).ToList();
            return GenerateSimpleEnum(title, pascalName, description, values, usings);
        }
    }

    // Case 4: Array at top level
    if (hasType && typeEl.GetString() == "array")
    {
        return GenerateArrayWrapper(title, pascalName, description, schema, usings);
    }

    // Case 5: Primitive or $ref at top level
    return GeneratePrimitiveWrapper(title, pascalName, description, schema, usings);
}

// ---------------------------------------------------------------------------
// Enum generation
// ---------------------------------------------------------------------------

string GenerateEnum(string title, string pascalName, string? description, List<JsonElement> variants, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"[JsonConverter(typeof(JsonStringEnumConverter<{pascalName}>))]");
    sb.AppendLine($"public enum {pascalName}");
    sb.AppendLine("{");

    for (int i = 0; i < variants.Count; i++)
    {
        var v = variants[i];
        var enumValue = v.GetProperty("enum").EnumerateArray().First().GetString()!;
        var memberDesc = GetString(v, "description");
        var memberName = ToPascalCase(enumValue);

        if (memberDesc != null)
        {
            sb.AppendLine("    /// <summary>");
            foreach (var line in memberDesc.Split('\n'))
                sb.AppendLine($"    /// {EscapeXml(line)}");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    [Description({EscapeCSharpString(memberDesc)})]");
        }
        sb.AppendLine($"    [JsonStringEnumMemberName(\"{enumValue}\")]");
        sb.Append($"    {memberName}");
        sb.AppendLine(i < variants.Count - 1 ? "," : "");
    }

    sb.AppendLine("}");
    return sb.ToString();
}

string GenerateSimpleEnum(string title, string pascalName, string? description, List<string> values, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"[JsonConverter(typeof(JsonStringEnumConverter<{pascalName}>))]");
    sb.AppendLine($"public enum {pascalName}");
    sb.AppendLine("{");

    for (int i = 0; i < values.Count; i++)
    {
        var v = values[i];
        var memberName = ToPascalCase(v);
        sb.AppendLine($"    [JsonStringEnumMemberName(\"{v}\")]");
        sb.Append($"    {memberName}");
        sb.AppendLine(i < values.Count - 1 ? "," : "");
    }

    sb.AppendLine("}");
    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Marker interface generation (pure $ref anyOf)
// ---------------------------------------------------------------------------

string GenerateMarkerInterface(string title, string pascalName, string? description, List<JsonElement> variants, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");

    // Store the $ref targets for roundtrip reconstruction
    var refs = variants
        .Where(v => v.TryGetProperty("$ref", out _))
        .Select(v => $"\"{v.GetProperty("$ref").GetString()!}\"")
        .ToList();
    if (refs.Count > 0)
        sb.AppendLine($"[JsonSchemaAnyOfRefs({string.Join(", ", refs)})]");

    sb.AppendLine($"public interface I{pascalName}");
    sb.AppendLine("{");
    sb.AppendLine("}");
    return sb.ToString();
}

// ---------------------------------------------------------------------------
// General anyOf → interface + variant classes
// ---------------------------------------------------------------------------

string GenerateAnyOfInterface(string title, string pascalName, string? description, List<JsonElement> variants, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"public interface I{pascalName}");
    sb.AppendLine("{");
    sb.AppendLine("}");
    sb.AppendLine();

    for (int i = 0; i < variants.Count; i++)
    {
        var v = variants[i];
        var variantName = $"{pascalName}Variant{i + 1}";
        var variantDesc = GetString(v, "description");

        if (v.TryGetProperty("$ref", out var refEl))
        {
            // $ref variant (possibly with description, type, and/or properties)
            var refTitle = refEl.GetString()!;
            var refType = ResolveRefType(refTitle, usings);
            var hasType = v.TryGetProperty("type", out var vtEl);
            var hasProps = v.TryGetProperty("properties", out var vPropsEl);

            if (hasType && hasProps)
            {
                // $ref + type + properties (e.g., Message variants)
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"[JsonSchemaRef(\"{refTitle}\")]");
                sb.AppendLine($"[JsonSchemaVariantType(\"{vtEl.GetString()}\")]");
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                EmitProperties(sb, vPropsEl, usings);
                sb.AppendLine("}");
            }
            else if (hasProps)
            {
                // $ref + properties (adjacently-tagged variant)
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"[JsonSchemaRef(\"{refTitle}\")]");
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                EmitProperties(sb, vPropsEl, usings);
                sb.AppendLine("}");
            }
            else
            {
                // Pure $ref variant with possible description
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"[JsonSchemaRef(\"{refTitle}\")]");
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                sb.AppendLine($"    public {refType} Value {{ get; set; }} = default!;");
                sb.AppendLine("}");
            }
        }
        else if (v.TryGetProperty("type", out var vtEl))
        {
            var vtype = vtEl.GetString();
            if (vtype == "null")
            {
                // null variant - skip
                continue;
            }
            else if (vtype == "object")
            {
                // Inline object variant
                AppendDescription(sb, variantDesc);
                EmitVariantAdditionalPropertiesAttributes(sb, v);
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                if (v.TryGetProperty("properties", out var voPropsEl))
                {
                    EmitProperties(sb, voPropsEl, usings);
                }
                sb.AppendLine("}");
            }
            else if (vtype == "array")
            {
                // Array variant
                var csType = ConvertArrayType(v, usings);
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                EmitArrayItemConstraintAttributes(sb, v, "    ");
                sb.AppendLine($"    public {csType} Value {{ get; set; }} = default!;");
                sb.AppendLine("}");
            }
            else
            {
                // Primitive variant
                var csType = JsonTypeToCSharp(vtype!, v, usings);
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                EmitPropertyConstraintAttributes(sb, v, "    ");
                sb.AppendLine($"    public {csType} Value {{ get; set; }} = default!;");
                sb.AppendLine("}");
            }
        }

        else if (v.TryGetProperty("anyOf", out var nestedAnyOf))
        {
            // Nested anyOf variant (e.g., nullable value: anyOf[{type: "string"}, {type: "null"}])
            var nestedVariants = nestedAnyOf.EnumerateArray().ToList();
            if (IsNullable(nestedVariants))
            {
                // Nullable value variant
                var nonNull = nestedVariants.First(vv => GetString(vv, "type") != "null");
                var csType = ConvertSchemaToType(nonNull, usings);
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                EmitPropertyConstraintAttributes(sb, nonNull, "    ");
                sb.AppendLine($"    [JsonSchemaNullable]");
                sb.AppendLine($"    public {csType}? Value {{ get; set; }}");
                sb.AppendLine("}");
            }
            else
            {
                // Non-nullable nested anyOf → treat as JsonElement
                usings.Add("System.Text.Json");
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"public class {variantName} : I{pascalName}");
                sb.AppendLine("{");
                sb.AppendLine($"    public JsonElement Value {{ get; set; }} = default!;");
                sb.AppendLine("}");
            }
        }
        else
        {
            // Bare variant (no type, no $ref, no anyOf) → empty schema (any JSON value)
            usings.Add("System.Text.Json");
            AppendDescription(sb, variantDesc);
            sb.AppendLine($"public class {variantName} : I{pascalName}");
            sb.AppendLine("{");
            sb.AppendLine($"    public JsonElement Value {{ get; set; }} = default!;");
            sb.AppendLine("}");
        }

        if (i < variants.Count - 1)
            sb.AppendLine();
    }

    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Nullable wrapper (top-level anyOf with 2 variants, one null)
// ---------------------------------------------------------------------------

string GenerateNullableWrapper(string title, string pascalName, string? description, JsonElement nonNullVariant, HashSet<string> usings)
{
    var csType = ConvertSchemaToType(nonNullVariant, usings);
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"public class {pascalName}");
    sb.AppendLine("{");
    EmitPropertyConstraintAttributes(sb, nonNullVariant, "    ");
    sb.AppendLine($"    public {csType}? Value {{ get; set; }}");
    sb.AppendLine("}");
    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Object class generation
// ---------------------------------------------------------------------------

string GenerateObjectClass(string title, string pascalName, string? description, JsonElement schema, JsonElement propsEl, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    if (schema.TryGetProperty("additionalProperties", out var addPropEl) && addPropEl.ValueKind == JsonValueKind.False)
    {
        sb.AppendLine("[JsonSchemaAdditionalProperties(false)]");
    }
    sb.AppendLine($"public class {pascalName}");
    sb.AppendLine("{");

    EmitProperties(sb, propsEl, usings);

    sb.AppendLine("}");
    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Flattened model (properties + anyOf)
// ---------------------------------------------------------------------------

string GenerateFlattenedModel(string title, string pascalName, string? description, JsonElement schema, JsonElement propsEl, JsonElement anyOfEl, HashSet<string> usings)
{
    var sb = new StringBuilder();
    var variants = anyOfEl.EnumerateArray().ToList();

    // Generate variant classes first
    for (int i = 0; i < variants.Count; i++)
    {
        var v = variants[i];
        var variantName = $"{pascalName}Variant{i + 1}";
        var variantDesc = GetString(v, "description");

        if (v.TryGetProperty("$ref", out var refEl))
        {
            var refTitle = refEl.GetString()!;
            var hasType = v.TryGetProperty("type", out var vtEl2);
            var hasVProps = v.TryGetProperty("properties", out var vPropsEl);

            if (hasType && hasVProps)
            {
                // $ref + type + properties
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"[JsonSchemaRef(\"{refTitle}\")]");
                sb.AppendLine($"[JsonSchemaVariantType(\"{vtEl2.GetString()}\")]");
                sb.AppendLine($"public class {variantName}");
                sb.AppendLine("{");
                EmitProperties(sb, vPropsEl, usings);
                sb.AppendLine("}");
                sb.AppendLine();
            }
            else if (hasVProps)
            {
                // $ref + properties (adjacently-tagged)
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"[JsonSchemaRef(\"{refTitle}\")]");
                sb.AppendLine($"public class {variantName}");
                sb.AppendLine("{");
                EmitProperties(sb, vPropsEl, usings);
                sb.AppendLine("}");
                sb.AppendLine();
            }
            else
            {
                // Pure $ref variant
                var refType2 = ResolveRefType(refTitle, usings);
                AppendDescription(sb, variantDesc);
                sb.AppendLine($"[JsonSchemaRef(\"{refTitle}\")]");
                sb.AppendLine($"public class {variantName}");
                sb.AppendLine("{");
                sb.AppendLine($"    public {refType2} Value {{ get; set; }} = default!;");
                sb.AppendLine("}");
                sb.AppendLine();
            }
        }
        else if (v.TryGetProperty("type", out var vtEl) && vtEl.GetString() == "object")
        {
            // Inline object variant
            AppendDescription(sb, variantDesc);
            EmitVariantAdditionalPropertiesAttributes(sb, v);
            sb.AppendLine($"public class {variantName}");
            sb.AppendLine("{");
            if (v.TryGetProperty("properties", out var voPropsEl))
            {
                EmitProperties(sb, voPropsEl, usings);
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }
        else
        {
            // Other variant (primitive, etc.)
            var csType = ConvertSchemaToType(v, usings);
            AppendDescription(sb, variantDesc);
            sb.AppendLine($"public class {variantName}");
            sb.AppendLine("{");
            EmitPropertyConstraintAttributes(sb, v, "    ");
            sb.AppendLine($"    public {csType} Value {{ get; set; }} = default!;");
            sb.AppendLine("}");
            sb.AppendLine();
        }
    }

    // Generate the main class
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"public class {pascalName}");
    sb.AppendLine("{");
    EmitProperties(sb, propsEl, usings);
    sb.AppendLine("}");
    return sb.ToString();
}

