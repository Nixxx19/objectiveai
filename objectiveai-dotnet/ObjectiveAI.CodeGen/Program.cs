    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Property emission
// ---------------------------------------------------------------------------

void EmitProperties(StringBuilder sb, JsonElement propsEl, HashSet<string> usings)
{
    var props = propsEl.EnumerateObject().OrderBy(p => p.Name).ToList();
    for (int i = 0; i < props.Count; i++)
    {
        var prop = props[i];
        var propName = prop.Name;
        var propSchema = prop.Value;
        var propDesc = GetString(propSchema, "description");
        var csPropName = ToPascalCase(propName);

        // Handle special chars in property names
        if (propName.StartsWith("$"))
            csPropName = ToPascalCase(propName.TrimStart('$'));

        if (propDesc != null)
        {
            sb.AppendLine("    /// <summary>");
            foreach (var line in propDesc.Split('\n'))
                sb.AppendLine($"    /// {EscapeXml(line)}");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine($"    [Description({EscapeCSharpString(propDesc)})]");
        }

        // JSON property name
        sb.AppendLine($"    [JsonPropertyName(\"{propName}\")]");

        // Determine type and constraints
        var (csType, isNullable) = ConvertPropertyType(propSchema, usings);

        // Emit constraint attributes
        EmitPropertySchemaAttributes(sb, propSchema, isNullable, "    ");

        // Default value
        string? defaultInit = null;
        if (propSchema.TryGetProperty("default", out var defaultEl))
        {
            defaultInit = ConvertDefaultValue(defaultEl, csType);
            var jsonDefault = defaultEl.GetRawText();
            sb.AppendLine($"    [JsonSchemaDefault({EscapeCSharpString(jsonDefault)})]");
        }

        // Emit property
        if (isNullable)
        {
            sb.AppendLine("    [JsonSchemaNullable]");
            var initValue = defaultInit ?? "null";
            if (csType.EndsWith("?"))
                sb.AppendLine($"    public {csType} {csPropName} {{ get; set; }} = {initValue};");
            else
                sb.AppendLine($"    public {csType}? {csPropName} {{ get; set; }} = {initValue};");
        }
        else
        {
            if (defaultInit != null)
                sb.AppendLine($"    public {csType} {csPropName} {{ get; set; }} = {defaultInit};");
            else
                sb.AppendLine($"    public {csType} {csPropName} {{ get; set; }} = default!;");
        }

        if (i < props.Count - 1)
            sb.AppendLine();
    }
}

// ---------------------------------------------------------------------------
// Type conversion
// ---------------------------------------------------------------------------

(string CsType, bool IsNullable) ConvertPropertyType(JsonElement schema, HashSet<string> usings)
{
    // Check for anyOf with null variant (nullable pattern)
    if (schema.TryGetProperty("anyOf", out var anyOfEl))
    {
        var variants = anyOfEl.EnumerateArray().ToList();
        if (IsNullable(variants))
        {
            var nonNull = variants.First(v => GetString(v, "type") != "null");
            var csType = ConvertSchemaToType(nonNull, usings);
            return (csType, true);
        }
        // Non-nullable anyOf in a property → use the schema type
        var typeName = ConvertSchemaToType(schema, usings);
        return (typeName, false);
    }

    // $ref (possibly with default alongside)
    if (schema.TryGetProperty("$ref", out var refEl))
    {
        var refTitle = refEl.GetString()!;
        var refType = ResolveRefType(refTitle, usings);
        return (refType, false);
    }

    // Regular type
    var type = ConvertSchemaToType(schema, usings);
    return (type, false);
}

string ConvertSchemaToType(JsonElement schema, HashSet<string> usings)
{
    // $ref
    if (schema.TryGetProperty("$ref", out var refEl))
    {
        return ResolveRefType(refEl.GetString()!, usings);
    }

    // anyOf (not at property level — standalone)
    if (schema.TryGetProperty("anyOf", out var anyOfEl))
    {
        var variants = anyOfEl.EnumerateArray().ToList();
        if (IsNullable(variants))
        {
            var nonNull = variants.First(v => GetString(v, "type") != "null");
            return ConvertSchemaToType(nonNull, usings) + "?";
        }
        usings.Add("System.Text.Json");
        return "JsonElement";
    }

    // enum
    if (schema.TryGetProperty("enum", out _))
    {
        return "string";
    }

    // type
    if (schema.TryGetProperty("type", out var typeEl))
    {
        var type = typeEl.GetString()!;
        return type switch
        {
            "string" => ConvertStringType(schema, usings),
            "integer" => ConvertIntegerType(schema),
            "number" => "double",
            "boolean" => "bool",
            "null" => "object",
            "array" => ConvertArrayType(schema, usings),
            "object" => ConvertObjectType(schema, usings),
            _ => "object"
        };
    }

    // Bare schema (no type, no $ref, no anyOf) → any JSON value
    usings.Add("System.Text.Json");
    return "JsonElement";
}

string ConvertStringType(JsonElement schema, HashSet<string> usings)
{
    if (schema.TryGetProperty("format", out var fmtEl))
    {
        var fmt = fmtEl.GetString();
        if (fmt == "date-time")
            return "DateTimeOffset";
    }
    return "string";
}

string ConvertIntegerType(JsonElement schema)
{
    if (schema.TryGetProperty("minimum", out var minEl) && schema.TryGetProperty("maximum", out var maxEl))
    {
        var minStr = minEl.GetRawText();
        // If min >= 0 and max > long.MaxValue → ulong
        if (minStr == "0")
        {
            var maxStr = maxEl.GetRawText();
            if (ulong.TryParse(maxStr, out var maxVal) && maxVal > (ulong)long.MaxValue)
                return "ulong";
        }
    }
    return "long";
}

string ConvertArrayType(JsonElement schema, HashSet<string> usings)
{
    if (schema.TryGetProperty("items", out var itemsEl))
    {
        var itemType = ConvertSchemaToType(itemsEl, usings);
        return $"List<{itemType}>";
    }
    usings.Add("System.Text.Json");
    return "List<JsonElement>";
}

string ConvertObjectType(JsonElement schema, HashSet<string> usings)
{
    if (schema.TryGetProperty("additionalProperties", out var apEl) && apEl.ValueKind != JsonValueKind.False)
    {
        // additionalProperties can be true (boolean) or an object (schema)
        if (apEl.ValueKind == JsonValueKind.True)
        {
            usings.Add("System.Text.Json");
            return "Dictionary<string, JsonElement>";
        }
        if (apEl.ValueKind == JsonValueKind.Object)
        {
            var valType = ConvertSchemaToType(apEl, usings);
            return $"Dictionary<string, {valType}>";
        }
    }
    if (!schema.TryGetProperty("properties", out _))
    {
        usings.Add("System.Text.Json");
        return "Dictionary<string, JsonElement>";
    }
    usings.Add("System.Text.Json");
    return "JsonElement";
}

