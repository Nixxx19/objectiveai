// Flattened ref model (properties + $ref at top level)
// ---------------------------------------------------------------------------

string GenerateFlattenedRefModel(string title, string pascalName, string? description, JsonElement schema, JsonElement propsEl, HashSet<string> usings)
{
    var sb = new StringBuilder();
    var refTitle = schema.GetProperty("$ref").GetString()!;
    var refType = ResolveRefType(refTitle, usings);

    // Generate a variant class for the ref
    var variantName = $"{pascalName}Variant1";
    sb.AppendLine($"[JsonSchemaRef(\"{refTitle}\")]");
    sb.AppendLine($"public class {variantName}");
    sb.AppendLine("{");
    sb.AppendLine($"    public {refType} Value {{ get; set; }} = default!;");
    sb.AppendLine("}");
    sb.AppendLine();

    // Generate the main class
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"public class {pascalName}");
    sb.AppendLine("{");
    EmitProperties(sb, propsEl, usings);
    sb.AppendLine("}");
    return sb.ToString();
}

// ---------------------------------------------------------------------------
// Array wrapper
// ---------------------------------------------------------------------------

string GenerateArrayWrapper(string title, string pascalName, string? description, JsonElement schema, HashSet<string> usings)
{
    var sb = new StringBuilder();
    AppendDescription(sb, description);
    sb.AppendLine($"[JsonSchemaTitle(\"{title}\")]");
    sb.AppendLine($"public class {pascalName}");
    sb.AppendLine("{");

    var itemType = "JsonElement";
    bool itemsNullable = false;
    if (schema.TryGetProperty("items", out var itemsEl))
    {
        // Check if items is nullable (anyOf with null variant)
        if (itemsEl.TryGetProperty("anyOf", out var itemAnyOf))
        {
            var itemVariants = itemAnyOf.EnumerateArray().ToList();
            if (IsNullable(itemVariants))
            {
                itemsNullable = true;
                var nonNull = itemVariants.First(v => GetString(v, "type") != "null");
                itemType = ConvertSchemaToType(nonNull, usings);
            }
            else
            {
                itemType = ConvertSchemaToType(itemsEl, usings);
            }
        }
        else
        {
            itemType = ConvertSchemaToType(itemsEl, usings);
        }
    }
    usings.Add("System.Text.Json");

    if (schema.TryGetProperty("minItems", out var minEl))
        sb.AppendLine($"    [JsonSchemaRange(Minimum = \"{minEl}\")]");
    if (schema.TryGetProperty("maxItems", out var maxEl))
        sb.AppendLine($"    [JsonSchemaRange(Maximum = \"{maxEl}\")]");

    if (itemsNullable)
        sb.AppendLine("    [JsonSchemaItemsNullable]");

    EmitArrayItemConstraintAttributes(sb, schema, "    ", skipNullableAttr: true);

    if (itemsNullable)
        sb.AppendLine($"    public List<{itemType}?> Items {{ get; set; }} = [];");
    else
        sb.AppendLine($"    public List<{itemType}> Items {{ get; set; }} = [];");

    sb.AppendLine("}");
    return sb.ToString();
}

