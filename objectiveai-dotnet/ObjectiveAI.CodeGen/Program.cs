string ResolveRefType(string refTitle, HashSet<string> usings)
{
    var pascalName = TitleToPascal(refTitle);
    var ns = GetNamespaceForTitle(refTitle);
    usings.Add(ns);

    if (IsInterfaceType(refTitle))
        return $"I{pascalName}";

    return pascalName;
}

string GetNamespaceForTitle(string title)
{
    var (dirPath, _) = TitleToPath(title);
    if (string.IsNullOrEmpty(dirPath))
        return "ObjectiveAI";
    var nsParts = dirPath.Split('/').Select(ToPascalCase);
    return "ObjectiveAI." + string.Join(".", nsParts);
}

// ---------------------------------------------------------------------------
// Naming helpers
// ---------------------------------------------------------------------------

string TitleToPascal(string title)
{
    var parts = Regex.Split(title, @"[._]").Where(s => s.Length > 0);
    return string.Concat(parts.Select(s => char.ToUpper(s[0]) + s[1..]));
}

string ToPascalCase(string s)
{
    if (string.IsNullOrEmpty(s)) return s;
    var parts = s.Split('_', '-', '.');
    return string.Concat(parts.Where(p => p.Length > 0).Select(p => char.ToUpper(p[0]) + p[1..]));
}

(string DirPath, string FileName) TitleToPath(string title)
{
    string? genericBase = null;
    foreach (var prefix in genericPrefixes)
    {
        if (title.StartsWith(prefix) && title.Length > prefix.Length)
        {
            genericBase = prefix.TrimEnd('.');
            break;
        }
    }

    var parts = (genericBase ?? title).Split('.');
    var typeName = parts.Last();
    var dirParts = parts.Take(parts.Length - 1).ToArray();
    var dirPath = string.Join("/", dirParts.Select(p => ToPascalCase(p)));
    var fileName = typeName;

    return (dirPath, fileName);
}

string FilePathToNamespace(string filePath)
{
    var parts = filePath.Split('/');
    if (parts.Length <= 1)
        return "ObjectiveAI";

    var nsParts = parts.Take(parts.Length - 1).Select(ToPascalCase);
    return "ObjectiveAI." + string.Join(".", nsParts);
}

List<string> DetectGenericPrefixes(HashSet<string> titles)
{
    var prefixes = new HashSet<string>();
    foreach (var title in titles)
    {
        var parts = title.Split('.');
        for (int i = 0; i < parts.Length - 1; i++)
        {
            if (parts[i].Length > 0 && char.IsUpper(parts[i][0]))
            {
                prefixes.Add(string.Join(".", parts.Take(i + 1)) + ".");
                break;
            }
        }
    }
    return prefixes.OrderBy(p => p).ToList();
}

// ---------------------------------------------------------------------------
// Schema inspection helpers
// ---------------------------------------------------------------------------

bool IsInterfaceType(string refTitle)
{
    if (!schemas.TryGetValue(refTitle, out var refSchema)) return false;
    if (!refSchema.TryGetProperty("anyOf", out var anyOfEl)) return false;
    if (refSchema.TryGetProperty("properties", out _)) return false;

    var variants = anyOfEl.EnumerateArray().ToList();
    // String enum anyOf → enum, not interface
    if (IsStringEnumAnyOf(variants)) return false;
    // Nullable (2 variants, one null) → class, not interface
    if (IsNullable(variants)) return false;
    // All other anyOf patterns at top level → interface
    return true;
}

bool IsStringEnumAnyOf(List<JsonElement> variants)
{
    if (variants.Count == 0) return false;
    return variants.All(v =>
        v.TryGetProperty("type", out var t) && t.GetString() == "string" &&
        v.TryGetProperty("enum", out var e) && e.GetArrayLength() == 1);
}

bool IsNullable(List<JsonElement> variants)
{
    if (variants.Count != 2) return false;
    return variants.Any(v => v.TryGetProperty("type", out var t) && t.GetString() == "null" && v.EnumerateObject().Count() == 1);
}

string? GetString(JsonElement el, string prop)
{
    if (el.TryGetProperty(prop, out var val) && val.ValueKind == JsonValueKind.String)
        return val.GetString();
    return null;
}

string ConvertDefaultValue(JsonElement defaultEl, string csType)
{
    if (defaultEl.ValueKind == JsonValueKind.String)
    {
        var strVal = defaultEl.GetString()!;
        // Check if the target type is an enum — if so, use the enum member name
        // Detect enum types: they are PascalCase type names that aren't basic types
        if (csType != "string" && csType != "object" && !csType.StartsWith("List<") && !csType.StartsWith("Dictionary<"))
        {
            // Check if the ref target is actually an enum
            foreach (var (title, schema) in schemas)
            {
                if (TitleToPascal(title) == csType)
                {
                    if (schema.TryGetProperty("anyOf", out var anyOfEl))
                    {
                        var variants = anyOfEl.EnumerateArray().ToList();
                        if (IsStringEnumAnyOf(variants))
                        {
                            return $"{csType}.{ToPascalCase(strVal)}";
                        }
                    }
                    if (schema.TryGetProperty("enum", out _))
                    {
                        return $"{csType}.{ToPascalCase(strVal)}";
                    }
                    break;
                }
            }
        }
        return $"\"{strVal}\"";
    }
    return defaultEl.ValueKind switch
    {
        JsonValueKind.True => "true",
        JsonValueKind.False => "false",
        JsonValueKind.Number => defaultEl.GetRawText(),
        JsonValueKind.Null => "null!",
        _ => "default!"
    };
}

// ---------------------------------------------------------------------------
// String helpers
// ---------------------------------------------------------------------------

void AppendDescription(StringBuilder sb, string? description)
{
    if (description == null) return;
    sb.AppendLine("/// <summary>");
    foreach (var line in description.Split('\n'))
        sb.AppendLine($"/// {EscapeXml(line)}");
    sb.AppendLine("/// </summary>");
    sb.AppendLine($"[Description({EscapeCSharpString(description)})]");
}

string EscapeXml(string s) => s
    .Replace("&", "&amp;")
    .Replace("<", "&lt;")
    .Replace(">", "&gt;");

string EscapeCSharpString(string s)
{
    // Use raw string literal if it contains special chars
    if (s.Contains('"') || s.Contains('\\') || s.Contains('\n') || s.Contains('\r'))
    {
        // Count max consecutive quotes
        int maxQuotes = 0;
        int current = 0;
        foreach (var c in s)
        {
            if (c == '"') { current++; maxQuotes = Math.Max(maxQuotes, current); }
            else current = 0;
        }
        var delim = new string('"', maxQuotes + 3);
        return $"{delim}\n{s}\n{delim}";
    }
    return $"\"{s}\"";
}

string JsonTypeToCSharp(string jsonType, JsonElement schema, HashSet<string> usings)
{
    return jsonType switch
    {
        "string" => ConvertStringType(schema, usings),
        "integer" => ConvertIntegerType(schema),
        "number" => "double",
        "boolean" => "bool",
        "array" => ConvertArrayType(schema, usings),
        "object" => ConvertObjectType(schema, usings),
        _ => "object"
    };
}

